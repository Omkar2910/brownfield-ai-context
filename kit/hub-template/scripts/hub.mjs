#!/usr/bin/env node
// hub.mjs — helper for the product context hub. Node 18+, no dependencies. Run from the hub repo root.
//
//   node scripts/hub.mjs map                          write context/system-map.md from catalog.json
//   node scripts/hub.mjs workspace <area|repo>...     write workspaces/<name>.code-workspace (+ direct non-platform dependencies)
//        [--no-deps] [--name <file-name>]
//   node scripts/hub.mjs impact <repo>                which repos depend on <repo> (calls, uses, loads)
//   node scripts/hub.mjs status                       per repo: cloned? kit installed? context check result
//   node scripts/hub.mjs clone <area|repo|all> [--run] print (or run) git clone for missing repos
//   node scripts/hub.mjs contracts [--sync]           compare services' API contracts with contracts/<service>/
//
// Repos are expected as sibling folders of the hub (change with "reposDir" in catalog.json).

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const hub = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(fs.readFileSync(path.join(hub, 'catalog.json'), 'utf8'));
const reposDir = path.resolve(hub, catalog.reposDir || '..');
const repos = catalog.repos;
const byName = new Map(repos.map(r => [r.name, r]));
const [cmd, ...rest] = process.argv.slice(2);
const flag = f => rest.includes(f);
const optVal = f => { const i = rest.indexOf(f); return i >= 0 ? rest[i + 1] : undefined; };
const words = rest.filter((a, i) => !a.startsWith('--') && !['--name'].includes(rest[i - 1]));
const repoDir = name => path.join(reposDir, name);
const cloned = name => fs.existsSync(path.join(repoDir(name), '.git'));
const deps = r => [...(r.calls || []), ...(r.uses || [])];
const TYPE_LABEL = { 'mfe-shell': 'Micro-frontend shell', 'mfe-remote': 'Micro-frontend', service: 'Backend service', library: 'Shared library' };
const TYPE_PLURAL = { 'mfe-shell': 'Micro-frontend shells', 'mfe-remote': 'Micro-frontends', service: 'Backend services', library: 'Shared libraries' };

function select(keys) {
  if (keys.includes('all')) return repos.map(r => r.name);
  const out = new Set();
  for (const k of keys) {
    if (byName.has(k)) out.add(k);
    for (const r of repos) if ((r.areas || []).includes(k)) out.add(r.name);
  }
  const unknown = keys.filter(k => !byName.has(k) && !repos.some(r => (r.areas || []).includes(k)));
  if (unknown.length) console.log(`Not in catalog (ignored): ${unknown.join(', ')}`);
  return [...out];
}

function dependents(name) {
  return repos.filter(r => deps(r).includes(name) || (r.loads || []).includes(name)).map(r => r.name);
}

// ---------------------------------------------------------------- map
function cmdMap() {
  const lines = [`# System map — ${catalog.product}`, '',
    '> Generated by `node scripts/hub.mjs map` from `catalog.json`. Edit the catalog, not this file.', ''];
  for (const type of ['mfe-shell', 'mfe-remote', 'service', 'library']) {
    const list = repos.filter(r => r.type === type);
    if (!list.length) continue;
    lines.push(`## ${TYPE_PLURAL[type]}`, '', '| Repo | What it does | Owner | Exposes / API | Depends on |', '| --- | --- | --- | --- | --- |');
    for (const r of list) {
      const exp = r.type === 'service' ? `\`${r.api || ''}\`` : (r.exposes || []).join('; ') || (r.loads ? `loads ${r.loads.join(', ')}` : '');
      lines.push(`| ${r.name} | ${r.description || ''} | ${r.owner || ''} | ${exp} | ${deps(r).join(', ') || '—'} |`);
    }
    lines.push('');
  }
  const mfes = repos.filter(r => r.type === 'mfe-remote' || r.type === 'mfe-shell');
  const services = repos.filter(r => r.type === 'service');
  if (mfes.length && services.length) {
    lines.push('## Which micro-frontend calls which API', '', `| | ${services.map(s => s.name).join(' | ')} |`, `| --- | ${services.map(() => '---').join(' | ')} |`);
    for (const m of mfes) lines.push(`| ${m.name} | ${services.map(s => ((m.calls || []).includes(s.name) ? '●' : '')).join(' | ')} |`);
    lines.push('', 'A change to a service API affects every micro-frontend marked in its column.', '');
  }
  lines.push('## Diagram', '', '```mermaid', 'graph LR');
  for (const r of repos) lines.push(`  ${r.name.replace(/-/g, '_')}["${r.name}"]`);
  for (const r of repos) {
    for (const c of r.calls || []) lines.push(`  ${r.name.replace(/-/g, '_')} -->|calls| ${c.replace(/-/g, '_')}`);
    for (const u of r.uses || []) lines.push(`  ${r.name.replace(/-/g, '_')} -.->|uses| ${u.replace(/-/g, '_')}`);
    for (const l of r.loads || []) lines.push(`  ${r.name.replace(/-/g, '_')} ==>|loads| ${l.replace(/-/g, '_')}`);
  }
  lines.push('```', '');
  const out = path.join(hub, 'context', 'system-map.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`wrote context/system-map.md (${repos.length} repos)`);
}

// ---------------------------------------------------------------- workspace
function cmdWorkspace() {
  if (!words.length) { console.log('Usage: hub.mjs workspace <area|repo>... [--no-deps] [--name <file-name>]'); process.exitCode = 2; return; }
  let names = select(words);
  if (!names.length) { console.log('No repos matched. Check the names and areas in catalog.json.'); process.exitCode = 2; return; }
  // Add direct dependencies, except platform repos (used by almost everything): name them to include them.
  const isPlatform = n => (byName.get(n).areas || []).includes('platform');
  const related = [...new Set(names.flatMap(n => deps(byName.get(n))))].filter(n => byName.has(n) && !names.includes(n));
  const skipped = related.filter(isPlatform);
  if (!flag('--no-deps')) names = [...names, ...related.filter(n => !isPlatform(n))];
  const order = ['service', 'library', 'mfe-remote', 'mfe-shell'];
  names.sort((a, b) => order.indexOf(byName.get(a).type) - order.indexOf(byName.get(b).type));
  const label = optVal('--name') || words.join('+');
  const wsDir = path.join(hub, 'workspaces');
  fs.mkdirSync(wsDir, { recursive: true });
  const folders = names.map(n => ({ name: `${n} (${TYPE_LABEL[byName.get(n).type].toLowerCase()})`, path: path.relative(wsDir, repoDir(n)).split(path.sep).join('/') }));
  folders.push({ name: 'product-context (hub)', path: '..' });
  const ws = { folders, settings: { 'chat.useAgentsMdFile': true } };
  const file = path.join(wsDir, `${label}.code-workspace`);
  fs.writeFileSync(file, JSON.stringify(ws, null, 2) + '\n');
  console.log(`wrote workspaces/${label}.code-workspace with ${names.length} repos + the hub:`);
  names.forEach(n => console.log(`  ${cloned(n) ? '✓' : '✗ not cloned'}  ${n}`));
  if (skipped.length) console.log(`Related platform repos not added (name them to include): ${skipped.join(', ')}`);
  if (names.length > 5) console.log('Tip: more than 5 repos in one window adds noise for the agent. Consider --no-deps or a narrower area.');
  if (names.some(n => !cloned(n))) console.log(`Clone missing repos with: node scripts/hub.mjs clone ${words.join(' ')} --run`);
}

// ---------------------------------------------------------------- impact
function cmdImpact() {
  const name = words[0];
  if (!name) { console.log('Usage: hub.mjs impact <repo>'); process.exitCode = 2; return; }
  if (!byName.has(name)) { console.log(`Unknown repo: ${name}`); process.exitCode = 2; return; }
  const direct = dependents(name);
  const second = [...new Set(direct.flatMap(dependents))].filter(n => n !== name && !direct.includes(n));
  console.log(`A change to ${name} can affect:`);
  console.log(`  directly:   ${direct.join(', ') || 'nothing in the catalog'}`);
  console.log(`  indirectly: ${second.join(', ') || '—'}`);
  console.log('Inside each repo, use "graphify affected <Class>" for code-level impact.');
}

// ---------------------------------------------------------------- status
function cmdStatus() {
  console.log(`Product: ${catalog.product}   (repos in ${reposDir})`);
  for (const r of repos) {
    const dir = repoDir(r.name);
    if (!cloned(r.name)) { console.log(`  ✗ ${r.name.padEnd(22)} not cloned`); continue; }
    const tool = ['.github/hooks/scripts/context-tools.cjs', '.claude/hooks/context-tools.cjs'].map(p => path.join(dir, p)).find(p => fs.existsSync(p));
    let result = 'kit not installed';
    if (tool) {
      try { result = execFileSync('node', [tool, 'check', '--repo', dir], { encoding: 'utf8' }); }
      catch (e) { result = (e.stdout || '') + ''; }
      result = (/Result: (.*)/.exec(result) || [, 'check failed to run'])[1];
    }
    const agents = fs.existsSync(path.join(dir, 'AGENTS.md')) ? 'AGENTS.md ✓' : 'no AGENTS.md';
    const graph = fs.existsSync(path.join(dir, 'graphify-out', 'graph.json')) ? 'code map ✓' : 'no code map';
    console.log(`  ✓ ${r.name.padEnd(22)} ${agents.padEnd(14)} ${graph.padEnd(12)} ${result}`);
  }
}

// ---------------------------------------------------------------- clone
function cmdClone() {
  const names = select(words.length ? words : ['all']).filter(n => !cloned(n));
  if (!names.length) { console.log('All selected repos are already cloned.'); return; }
  for (const n of names) {
    const url = byName.get(n).clone || (catalog.cloneUrlPattern || '').replace('{name}', n);
    console.log(`git clone ${url} ${repoDir(n)}`);
    if (flag('--run')) execFileSync('git', ['clone', url, repoDir(n)], { stdio: 'inherit' });
  }
  if (!flag('--run')) console.log('(add --run to clone them now)');
}

// ---------------------------------------------------------------- contracts
function cmdContracts() {
  for (const s of repos.filter(r => r.type === 'service' && r.contract)) {
    const src = path.join(repoDir(s.name), s.contract);
    const dest = path.join(hub, 'contracts', s.name, path.basename(s.contract));
    const users = repos.filter(r => (r.calls || []).includes(s.name)).map(r => r.name);
    if (!fs.existsSync(src)) { console.log(`  ? ${s.name.padEnd(20)} contract not found locally (${cloned(s.name) ? s.contract : 'repo not cloned'})`); continue; }
    const same = fs.existsSync(dest) && fs.readFileSync(dest, 'utf8') === fs.readFileSync(src, 'utf8');
    if (same) { console.log(`  = ${s.name.padEnd(20)} up to date`); continue; }
    if (flag('--sync')) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(src, dest);
      console.log(`  ↻ ${s.name.padEnd(20)} copied to contracts/${s.name}/ — used by: ${users.join(', ') || 'no catalogued caller'}`);
    } else {
      console.log(`  ≠ ${s.name.padEnd(20)} differs from the hub copy — used by: ${users.join(', ') || 'no catalogued caller'} (run with --sync)`);
    }
  }
}

const commands = { map: cmdMap, workspace: cmdWorkspace, impact: cmdImpact, status: cmdStatus, clone: cmdClone, contracts: cmdContracts };
if (commands[cmd]) commands[cmd]();
else console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 12).map(l => l.replace(/^\/\/ ?/, '')).join('\n'));
